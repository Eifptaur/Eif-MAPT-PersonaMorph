#: 「动机」提权的可机械判据：`motive` 字段非空且**不是**抽象词。
#  ⛔ 抽象词表是**负向**的（命中即判"只写了抽象词"）—— 因为"写得好的动机"没法穷举，
#     但"像口号一样的抽象词"是有限的、可以列出来。
MOTIVE_ABSTRACT_HINTS = ("变强", "更强", "守护", "拯救", "复仇", "自由", "和平",
                         "正义", "完美", "无敌", "第一", "活下去")


def motive_ok(card: dict) -> bool:
    """`motive` 是否**明确到可以用**（非空 · 不太短 · 不是抽象口号）。

    这是"给动机加权"的**机械那一半**：判据能自己判的就不该交给模型裁判。

    ⛔ 三条门槛，各自管一类废动机，**不许合并**（合并了就没法定位是哪条在拦）：
      ① **空 / <6 字符** —— 压根没写（"想赢"这种撑不起一张卡）；
      ② **通篇都是口号** —— 去掉"想要/为了/的"之后，整段**只是**一个抽象词或其同义扩展
         （"想要变强"、"想要变得更强一些"都算）；
         判法＝剥掉修饰后**剩下的字符几乎全是抽象词**（而不是"里面出现了抽象词就算"——
         那会误伤"为了变强而偷偷练剑"这种**有具体手段**的真动机）；
      ③ 具体动机（含缘由 / 手段 / 对象）⇒ 通过。
    """
    _m = str((card or {}).get("motive") or "").strip()
    if len(_m) < 6:
        return False
    # 剥掉纯修饰词；剩下的长度＝"有没有实质内容"
    _bare = _m
    for _w in ("想要", "为了", "希望", "变得", "一点", "一些", "的", "能", "可以"):
        _bare = _bare.replace(_w, "")
    _bare = _bare.strip("，。！ ").strip()
    if not _bare:
        return False
    # ⛔ 判据：**剩下的字符里，抽象词占了一半以上** ⇒ 判"只写了口号"。
    #    用占比而不是"包含"：这样"为了变强而偷偷练剑"（抽象词 2 / 剩 8）能过，
    #    而"想要变得更强一些"（剥完剩"更强大"，几乎全是抽象词）过不了。
    _hit = sum(1 for h in MOTIVE_ABSTRACT_HINTS if h in _bare)
    _abstract_chars = 0
    for h in MOTIVE_ABSTRACT_HINTS:
        if h in _bare:
            _abstract_chars = max(_abstract_chars, len(h))
    return not (_hit and len(_bare) <= max(4, _abstract_chars + 1))


