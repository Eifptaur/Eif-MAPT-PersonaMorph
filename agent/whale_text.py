def popup_help_text(chat: str, *, whale: bool = False) -> dict:
    """按文案风格取「开窗求助」弹窗的标题与正文 ⇒ `{title, body}`（**唯一组装点**）。

    ⛔ 前端**不许**自己拼这两句（两处写必然漂移）；要改文案只改上面两个字典。
    """
    src = POPUP_HELP_WHALE if whale else POPUP_HELP
    return {"title": str(src["title"]),
            "body": str(src["body"]).replace("{chat}", str(chat or "某个会话"))}
