def all_unicode() -> list:
    """全部 Unicode 表情（去重，保序）。"""
    seen, out = set(), []
    for _g, arr in UNICODE_GROUPS.items():
        for c in arr:
            if c and c not in seen:
                seen.add(c)
                out.append(c)
    return out


